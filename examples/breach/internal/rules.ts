// ── /examples/breach · the rules ──────────────────────────────────────────
// BREACH is a 2v2 tabletop skirmish played on the armornet globe. One side runs
// a supply-chain intrusion; the other runs the estate it is aimed at. The board
// is the same four-territory sphere the console's overview draws, so a player
// who learns this map has learned where a real compromise happens.
//
// ── This file used to BE the rules. It is now a thin layer over them ─────────
// The board, the roster, the deck and the upgrade tracks were ~450 lines of
// hand-authored literals here, and ~450 more in Go, and nothing checked one
// against the other. They agreed until somebody rebalanced a card, and then the
// client lit a target the server refused.
//
// They now come from `rules.gen.ts`, generated by `cmd/breachgen` out of the
// canonical `internal/breach/{rules,cards}.yaml`. Re-exported from here so that
// every component keeps importing what it always imported — the data moved, the
// module boundary did not.
//
// ── What is still authored here, and why ────────────────────────────────────
// The pure functions the standalone demo INTERPRETS the generated data with:
// the outcome bands, the 2d6 distribution, the odds arithmetic, the ownership
// test. They are the same rules the Go engine applies, and they are duplicated
// on purpose and only for the no-backend demo — `showcase` is a component
// library and an example that needs a Go server and a database to open is an
// example nobody opens.
//
// The safety property that makes that duplication acceptable: they can only
// ever run when there is no authority to disagree with. `BreachMatch.perform`
// refuses to resolve anything once `remote` is set, so on a real table these
// functions price the HUD and decide nothing. See the note there.
//
// If you are adding a rule: it goes in `internal/breach` first. It comes here
// only if the offline demo cannot work without it.

