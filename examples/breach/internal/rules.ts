/** The chairs in play at a given size, as klass keys in initiative order.
 *  One seat per side at 1v1, taking the first of each — so the order alternates
 *  at every size and `phase` keeps meaning the same thing. */
export function seatOrder(size: MatchSize): string[] {
	if (size === '1v1') {
		const first = (f: Faction) => INITIATIVE.find((k) => klassByKey(k).faction === f)!;
		return [first('red'), first('blue')];
	}
	return [...INITIATIVE];
}

