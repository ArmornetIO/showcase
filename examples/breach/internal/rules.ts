/**
 * The four signature powers — one per class, and the closest thing the deck has
 * to a protagonist's move.
 *
 * Worth naming because they are a CATEGORY the generated accessors do not
 * expose. `CATALOGUE` is the cards a side can hold and `abilitiesOf` reads out
 * of it; a signature lives on the klass instead, so every list-shaped question
 * about "all the playable moves" silently answers four short.
 *
 * The property that makes this set useful elsewhere: every one is `uses: 1`.
 * A signature is burned once a game by the one class that has it, which means
 * anything hung off this list is rare BY THE RULES rather than by somebody
 * remembering to be sparing.
 */
export const SIGNATURES: Array<{ klass: Klass; power: PowerDef }> = ROSTER.flatMap((k) =>
	k.power ? [{ klass: k, power: k.power }] : []
);

export const isSignature = (key: string): boolean =>
	SIGNATURES.some((s) => s.power.key === key);

/**
 * The display name of any playable card, wherever the generator put it.
 *
 * `abilityByKey` only searches `CATALOGUE`, so it structurally cannot find the
 * four klass SIGNATURE powers — Zero-Day Reserve among them, which is the
 * loudest card in the game. Anything starting from a card KEY rather than from
 * a seat wants both lists, and the failure is quiet in the worst way: the
 * lookup returns undefined and the caller renders a slug.
 *
 * Here rather than in `rules.gen.ts` because that file is generated from the Go
 * rules and an accessor added to it does not survive the next regeneration.
 */
export const cardNameFor = (key: string): string =>
	abilityByKeyGen(key)?.name ?? ROSTER.find((k) => k.power?.key === key)?.power?.name ?? key;

// ── Outcome ──────────────────────────────────────────────────────────────────
// How well it went — the dice say degree, not just yes or no.
//
// The number printed on the card is what a CLEAN roll gets you. Everything else
// is measured against that, which means one table covers every card in the game
// and a player only ever has to learn it once.
//
//   botch     −5 or worse. It goes wrong in a way that costs you something.
//   fail      short of the mark, including an exact tie — ties go to the defender.
//   partial   just over. Half the printed effect, rounded up.
//   clean     +4 or better. Exactly what the card says.
//   critical  +8 or better. The card, and then some.

export const OUTCOME_LABEL: Record<Outcome, string> = {
	botch: 'BOTCHED',
	fail: 'FAILED',
	partial: 'PARTIAL',
	clean: 'CLEAN',
	critical: 'CRITICAL'
};

export const OUTCOME_COLOR: Record<Outcome, string> = {
	botch: '#EF4444',
	fail: '#94A3B8',
	partial: '#FBBF24',
	clean: '#34D399',
	critical: '#7DD3FC'
};

export const outcomeFor = (margin: number): Outcome =>
	margin <= -5
		? 'botch'
		: margin <= 0
			? 'fail'
			: margin <= 3
				? 'partial'
				: margin <= 7
					? 'clean'
					: 'critical';

export const succeeded = (o: Outcome) => o === 'partial' || o === 'clean' || o === 'critical';

/** The printed number, scaled by how well the roll went. */
export function scaleEffect(o: Outcome, base: number): number {
	if (!succeeded(o)) return 0;
	if (o === 'partial') return Math.max(1, Math.ceil(base / 2));
	if (o === 'critical') return base + 1;
	return base;
}

// ── Where a card may be played ───────────────────────────────────────────────

/**
 * The default is the obvious one and it is worth stating: you may act on ground
 * the other side owns, and on the neutral supply chain both sides live off. You
 * may NOT act on your own — attacking your own registry is not a move, and
 * hardening the enemy's relay is not either.
 *
 * `ability.on` overrides it, which is how blue gets a counter-offensive: a card
 * naming `['red']` reaches into the staging grounds, and that is the only way
 * the defenders ever get to be the ones arriving somewhere.
 */
export function canTarget(a: Ability, s: Structure, actor: Faction): boolean {
	if (a.targets && !a.targets.includes(s.id)) return false;
	const allowed: Owner[] = a.on ?? ['neutral', actor === 'red' ? 'blue' : 'red'];
	// Blue's estate-tending cards (harden, quarantine, rebuild) are the exception
	// the default cannot express: they act on blue's OWN ground.
	return allowed.includes(s.owner);
}

