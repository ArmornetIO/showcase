/**
 * A seat, as the renderer needs it.
 *
 * The generated `Klass` types `shape` as a plain string, because Go has no
 * union type to carry the four silhouettes and the engine never reads the
 * field. The renderer does, and `CharacterSkin` is how it says so — so the
 * widening happens exactly here, once, rather than at every draw site.
 */
export type Klass = Omit<GenKlass, 'shape'> & CharacterSkin;

export const ROSTER: Klass[] = GEN_ROSTER as Klass[];

export const klassByKey = (k: string): Klass => ROSTER.find((r) => r.key === k) ?? ROSTER[0];

