// ── Resolution ───────────────────────────────────────────────────────────────
// 2d6 + modifiers against the building's hardening. Ties go to the defender —
// an attack that only just works did not work. A margin of 4 or better plants a
// PERSISTENT foothold, which survives the first eviction: this is why real
// intrusions are cheap to start and expensive to remove.

const TWO_D6_COUNTS = [0, 0, 1, 2, 3, 4, 5, 6, 5, 4, 3, 2, 1];

/** Probability that 2d6 lands at or above `n`. */
export function oddsAtLeast(n: number): number {
	if (n <= 2) return 1;
	if (n > 12) return 0;
	let c = 0;
	for (let s = n; s <= 12; s++) c += TWO_D6_COUNTS[s];
	return c / 36;
}

// ── Dice ─────────────────────────────────────────────────────────────────────
// The throw is a seam rather than a call to `Math.random`, for the same reason
// Go's `Rand` is one (internal/breach/errors.go): the dice decide the game, so a
// test has to be able to say what they landed on. A rules test that can only
// assert "something happened" is not a rules test.

/** Where a throw gets its numbers. `intN` returns a value in [0, n), which is
 *  the shape Go's `Rand` has — so one script of values pins both engines. */
export interface DiceSource {
	intN(n: number): number;
}

/** What a real table rolls with. */
export const DICE: DiceSource = { intN: (n) => Math.floor(Math.random() * n) };

/** Replays a script of values, then repeats its last one forever. The TS half of
 *  Go's `FixedRand`, down to the clamping, so a golden vector written against
 *  one engine reads the same in the other. */
export function fixedDice(values: number[]): DiceSource {
	let at = 0;
	return {
		intN: (n) => {
			if (n <= 0 || !values.length) return 0;
			return Math.abs(values[Math.min(at++, values.length - 1)]) % n;
		}
	};
}

/** A throw nobody ruled on, agreed between browsers.
 *
 *  The faces swatted out of the air at a seal decide nothing, so the server
 *  never sends them — but two players sitting next to each other watching
 *  different numbers get swatted read it as the dice being out of sync. Seeded
 *  off the resolution's seq, which every client at the table already has. */
export function seededDice(seed: number): DiceSource {
	let s = (seed * 2654435761) >>> 0 || 1;
	return {
		intN: (n) => {
			// xorshift32 — the point is that it is the SAME sequence everywhere,
			// not that it is a good generator.
			s ^= s << 13;
			s ^= s >>> 17;
			s ^= s << 5;
			s >>>= 0;
			return n <= 0 ? 0 : s % n;
		}
	};
}

export function roll2d6(src: DiceSource = DICE): { dice: [number, number]; total: number } {
	const a = 1 + src.intN(6);
	const b = 1 + src.intN(6);
	return { dice: [a, b], total: a + b };
}

export interface Odds {
	/** Everything the actor adds to the dice, itemised — the HUD shows the parts
	 *  because "+7" tells a player nothing about which of their choices earned it. */
	skill: number;
	abilityMod: number;
	resourceMod: number;
	/** What the ground you already hold is worth on this roll — see `leverage`. */
	holdMod: number;
	modifier: number;
	/** The number to beat: a building's live hardening, or the card's own DC. */
	target: number;
	/** What the dice alone must reach for each band. Ties go to the defender, so
	 *  the first success is at target + 1. */
	needed: number;
	neededClean: number;
	/** Probability of at least a partial, and of at least a clean. */
	chance: number;
	chanceClean: number;
	/** Chance the roll goes badly enough to cost you something. */
	chanceBotch: number;
}

export function computeOdds(opts: {
	/** The building's hardening, when a building is defending. */
	hardening?: number;
	/** The card's own difficulty, when nothing is. */
	dc?: number;
	skill: number;
	abilityMod: number;
	resourceMod: number;
	holdMod?: number;
	defenceMod: number;
}): Odds {
	const hold = opts.holdMod ?? 0;
	const modifier = opts.skill + opts.abilityMod + opts.resourceMod + hold;
	const target = (opts.hardening ?? opts.dc ?? 8) + opts.defenceMod;
	const needed = target - modifier + 1;
	const neededClean = target - modifier + 4;
	// A botch is margin ≤ −5, i.e. the dice landing at or below target − 5 − mod.
	const botchAtMost = target - modifier - 5;
	return {
		skill: opts.skill,
		abilityMod: opts.abilityMod,
		resourceMod: opts.resourceMod,
		holdMod: hold,
		modifier,
		target,
		needed,
		neededClean,
		chance: oddsAtLeast(needed),
		chanceClean: oddsAtLeast(neededClean),
		chanceBotch: 1 - oddsAtLeast(botchAtMost + 1)
	};
}

